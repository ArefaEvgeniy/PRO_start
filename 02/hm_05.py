# 1. Створити базовий клас BankAccount
# Атрибути:
# owner — власник рахунку;
# account_number — номер рахунку;
# _balance — поточний баланс.
# Методи:
# Меьтод				Призначення
# deposit(amout)			Поповнення рахунку
# withdraw(amount)		Зняття коштів
# transfer(other_account, amount)	Переказ коштів на інший рахунок
# get_balance()			Отримання поточного балансу
#
# 2. Реалізувати інкапсуляцію
# Передбачити такі обмеження:
# Баланс не можна змінювати безпосередньо через публічний атрибут.
# Не можна поповнити рахунок від'ємною або нульовою сумою.
# Не можна зняти більше коштів, ніж є на рахунку.
# Не можна переказати кошти на той самий рахунок.
# У разі некоректних операцій виводити відповідне повідомлення.
#
# 3. Реалізувати наслідування
# Створити два дочірні класи:
# SavingsAccount — накопичувальний рахунок
#
# Додаткові можливості:
# зберігання відсоткової ставки;
# метод add_interest() для нарахування відсотків.
# BusinessAccount — бізнес-рахунок
#
# Додаткові можливості:
# встановлення кредитного ліміту;
# можливість здійснювати платежі в межах доступного кредитного ліміту.
#
# 4. Реалізувати магічні методи
# У класі BankAccount реалізувати:
# __str__() — зручне представлення рахунку;
# __eq__() — порівняння рахунків за номером;
# __lt__() — порівняння рахунків за балансом.
#
# 5. Перевірити роботу
# Створити:
# два звичайні банківські рахунки;
# один накопичувальний рахунок;
# один бізнес-рахунок.
# Продемонструвати поповнення, зняття, переказ, нарахування відсотків,
# порівняння рахунків та спробу зробити заборонені дії.
